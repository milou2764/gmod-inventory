"""The compatible addons' fits on every playermodel: the tools' source and the game's packed file.

tools/data/fits_compat.lua (written by fit_compat.py, patched by fit_locks.py, read by the sheets and the
fit editor): "x y z pitch yaw roll size" per playermodel of M, "|" between them, per item class.
lua/advinv/cl_fits_compat.lua (shipped): the same fits, one line per playermodel (every item in turn)
in one LZMA blob, merged into AdvInv.Fits[playermodel] the first time one of that playermodel's fits is
asked for. 1,300 playermodels x 1,160 items would otherwise be 4 MB of Lua and 1.5 million tables made
at load.

    python fits_compat_io.py        (packs the source into the game's file)
"""
import base64
import lzma
import re
import struct
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
SRC = TOOLS / "data" / "fits_compat.lua"
GAME = TOOLS.parent / "lua" / "advinv" / "cl_fits_compat.lua"


def read(path=SRC):
    """-> (models, {class: [fit text per model]})"""
    t = Path(path).read_text(encoding="utf-8")
    models = re.findall(r'^    "([^"]+)",$', t.split("local F")[0], re.M)
    items = {cls: packed.split("|") for cls, packed in re.findall(r'^    (\w+) = "([^"]*)",$', t, re.M)}
    return models, items


_DECODER = r"""AdvInv.Fits = AdvInv.Fits or {}
local data -- the decompressed lines (false: couldn't be read)
local function lines()
    if data == nil then
        data = util.Decompress(util.Base64Decode(P.blob) or "") or false
        if data and #data ~= P.size then data = false end
        if not data then ErrorNoHalt("[AdvInv] compatible items' fits: can't decompress them\n") end
        P.blob = nil
    end
    return data
end
-- this playermodel's fits, into its table (never over a fit already there)
local function merge(t, k)
    local s = lines()
    if not s then return end
    local off, len = P.at[k * 2 - 1], P.at[k * 2]
    if len == 0 then return end
    local i, C = 0, P.classes
    for e in string.gmatch(string.sub(s, off + 1, off + len) .. "|", "([^|]*)|") do
        i = i + 1
        local class = C[i]
        if e ~= "" and class and rawget(t, class) == nil then
            local n = {}
            for x in string.gmatch(e, "%S+") do n[#n + 1] = tonumber(x) end
            rawset(t, class, { Vector(n[1], n[2], n[3]), Angle(n[4], n[5], n[6]), n[7] })
        end
    end
end
local index = {}
for k, model in ipairs(P.models) do index[string.lower(model)] = k end
-- (merged on the first lookup of a fit missing from a playermodel's table: cl_fits.lua)
AdvInv.AddFitSource(index, function(t, model) merge(t, index[model]) end)"""


def pack(src=SRC, out=GAME):
    models, items = read(src)
    classes = list(items)
    lines, at, seen = [], [], {}
    blob = bytearray()
    for k in range(len(models)):
        line = "|".join(items[c][k] if k < len(items[c]) else "" for c in classes).rstrip("|")
        if not line.replace("|", ""):
            at += [0, 0]
            continue
        if line not in seen:  # (playermodels with the same fits share one line)
            seen[line] = len(blob)
            blob += line.encode("ascii")
        at += [seen[line], len(line)]
    z = bytearray(lzma.compress(bytes(blob), format=lzma.FORMAT_ALONE, preset=9 | lzma.PRESET_EXTREME))
    z[5:13] = struct.pack("<Q", len(blob))  # (the real size: util.Decompress reads it)
    b64 = base64.b64encode(bytes(z)).decode("ascii")
    L = ["-- Generated by tools/fits_compat_io.py from tools/data/fits_compat.lua (fit_compat.py; never by",
         "-- hand): the compatibility items (sh_compat_data.lua) fitted to each playermodel, packed. Each",
         "-- playermodel's fits are merged into AdvInv.Fits the first time one of them is asked for.",
         "local P = {",
         "    classes = { " + ", ".join(f'"{c}"' for c in classes) + " },",
         "    models = {"]
    L += [f'        "{m}",' for m in models]
    L.append("    },")
    L.append("    at = { " + ", ".join(str(x) for x in at) + " },")
    L.append(f"    size = {len(blob)},")
    L.append("    blob = table.concat({")
    L += [f'        "{b64[k:k + 4000]}",' for k in range(0, len(b64), 4000)]
    L.append("    }),")
    L.append("}")
    L.append(_DECODER)
    Path(out).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    return Path(out).stat().st_size


def unpack(path=GAME):
    """The game's file back to (models, {class: [fit text per model]}) (checks)."""
    t = Path(path).read_text(encoding="utf-8")
    classes = re.findall(r'"([^"]*)"', re.search(r"^    classes = \{ (.*) \},$", t, re.M).group(1))
    models = re.findall(r'^        "([^"]+)",$', t.split("    at = ")[0], re.M)
    at = [int(x) for x in re.search(r"^    at = \{ (.*) \},$", t, re.M).group(1).split(",")]
    b64 = "".join(re.findall(r'^        "([A-Za-z0-9+/=]+)",$', t[t.index("    blob = table.concat({"):], re.M))
    z = base64.b64decode(b64)
    d, dict_size, size = z[0], struct.unpack_from("<I", z, 1)[0], struct.unpack_from("<Q", z, 5)[0]
    dec = lzma.LZMADecompressor(format=lzma.FORMAT_RAW, filters=[
        {"id": lzma.FILTER_LZMA1, "lc": d % 9, "lp": (d // 9) % 5, "pb": d // 45, "dict_size": dict_size}])
    blob = dec.decompress(z[13:], max_length=size).decode("ascii")
    items = {c: [""] * len(models) for c in classes}
    for k in range(len(models)):
        off, n = at[2 * k], at[2 * k + 1]
        for i, e in enumerate(blob[off:off + n].split("|") if n else []):
            items[classes[i]][k] = e
    return models, items


if __name__ == "__main__":
    print(f"-> {GAME} ({pack() // 1024} KB)")
