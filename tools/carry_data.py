"""Reads and patches lua/advinv/cl_carry_data.lua (written by fit_carry.py): the carry offsets of the
long guns per offset set, weapon class and mode, and which set each playermodel uses.

Carry positions are approved in the fit editor like worn items, under the class "carry:<weapon
class>:<mode>" (CARRY_PREFIX): their fit is the position and angles on the mode's bone (no size).
"""
import base64
import lzma
import re
import struct
from pathlib import Path

# A negative zero ("-0.00", "-0.0") written without its sign; only a number that is all zeros
# ("-0.004" keeps its sign: a plain .replace("-0.00", "0.00") turned it into 0.004).
_NEG_ZERO = re.compile(r"(?<![\w.])-(0\.0+)(?![0-9])")  # (not "1-0.00")


def _nz(text):
    return _NEG_ZERO.sub(lambda m: m.group(1), text)


TOOLS = Path(__file__).resolve().parent
PATH = TOOLS.parent / "lua" / "advinv" / "cl_carry_data.lua"
CARRY_PREFIX = "carry:"

_NUM = r"(-?[\d.]+)"
_ENTRY = re.compile(rf'^            (\w+) = \{{ "([^"]+)", V\({_NUM}, {_NUM}, {_NUM}\), A\({_NUM}, {_NUM}, {_NUM}\), (V\([^)]*\)) \}},$')


def gear_class(weapon, mode):
    return f"{CARRY_PREFIX}{weapon}:{mode}"


def split_class(cls):
    """'carry:weapon_ar2:sling_up' -> ('weapon_ar2', 'sling_up'), or None for another item."""
    if not cls.startswith(CARRY_PREFIX):
        return None
    weapon, _, mode = cls[len(CARRY_PREFIX):].partition(":")
    return weapon, mode


# The file is packed (18 MB of Lua for 1,300 playermodels otherwise): the names in tables, every set's
# entries as fixed-size records in one LZMA blob (base64), decoded in game set by set on first use.
#   offset record (16 bytes): class, mode, bone, outward direction (1-based indexes, u8), position x100
#     and angles x10 (int16 each);
#   stack record (6 bytes): launcher class, mode, primary class, mode (u8), push x100 (int16).
_REC, _STACK = struct.Struct("<BBBB3h3h"), struct.Struct("<BBBBh")


def _lua_str_list(name, items):
    return f"    {name} = {{ " + ", ".join(f'"{x}"' for x in items) + " },"


def write(data, path=PATH):
    """data: sets[set][weapon][mode] = {bone, pos, ang, out}, reps[set] = playermodel, stack[set][key] =
    push, aliases[playermodel] = set, templates (Lua lines), models (list)."""
    sets, reps, stack = data["sets"], data.get("reps", {}), data.get("stack", {})
    classes, modes, bones, outs = {}, {}, {}, {}

    def ix(d, k):
        if k not in d:
            d[k] = len(d) + 1
            assert d[k] < 256, "more than 255 names"
        return d[k]

    blob, index = bytearray(), []
    for name, s in sets.items():
        off, n = len(blob), 0
        for cls, per in s.items():
            for mode, e in per.items():
                o = tuple(round(x * 1000) for x in e["out"])
                blob += _REC.pack(ix(classes, cls), ix(modes, mode), ix(bones, e["bone"]), ix(outs, o),
                                  *(round(x * 100) for x in e["pos"]), *(round(x * 10) for x in e["ang"]))
                n += 1
        soff, sn = len(blob), 0
        for key, push in sorted(stack.get(name, {}).items()):
            a, b = key.split("|")
            (ca, ma), (cb, mb) = a.split(" "), b.split(" ")
            blob += _STACK.pack(ix(classes, ca), ix(modes, ma), ix(classes, cb), ix(modes, mb), round(push * 100))
            sn += 1
        index.append((name, off, n, soff, sn))
    z = bytearray(lzma.compress(bytes(blob), format=lzma.FORMAT_ALONE, preset=9 | lzma.PRESET_EXTREME))
    z[5:13] = struct.pack("<Q", len(blob))  # (the real size, not "unknown": util.Decompress reads it)
    b64 = base64.b64encode(bytes(z)).decode("ascii")

    def order(d):
        return [k for k, _ in sorted(d.items(), key=lambda kv: kv[1])]

    L = ["-- Generated by tools/fit_carry.py; read and written by tools/carry_data.py (never by hand;",
         "-- tune in game with advinv_carry_tune). CarryOffsets[set][weapon class][mode] = { bone, position,",
         "-- angles, outward direction }, CarryStack[set][\"launcher mode|primary class mode\"] = push: packed,",
         "-- each set decoded on first use (records: tools/carry_data.py).",
         "local V, A = Vector, Angle",
         "local P = {",
         _lua_str_list("classes", order(classes)),
         _lua_str_list("modes", order(modes)),
         _lua_str_list("bones", order(bones)),
         "    outs = { " + ", ".join(str(c) for o in order(outs) for c in o) + " },",
         "    index = {"]
    for name, off, n, soff, sn in index:
        L.append(f'        ["{name}"] = {{ {off}, {n}, {soff}, {sn} }},')
    L.append("    },")
    L.append("    reps = {")
    for name in sets:
        if reps.get(name):
            L.append(f'        ["{name}"] = "{reps[name]}",')
    L.append("    },")
    L.append(f"    size = {len(blob)},")
    L.append("    blob = table.concat({")
    for k in range(0, len(b64), 4000):
        L.append(f'        "{b64[k:k + 4000]}",')
    L.append("    }),")
    L.append("}")
    L.append(_LUA_DECODER)
    L.append("-- playermodel -> offset set (models with the same proportions share one)")
    L.append("AdvInv.CarryAliases = {")
    for m, name in data["aliases"].items():
        L.append(f'    ["{m}"] = "{name}",')
    L.append("}")
    L.append("-- weapons without offsets: surface point, outward direction and angles of each mode on the")
    L.append("-- default body, placed at run time with the weapon's own shape")
    L.append("AdvInv.CarryTemplates = {")
    L.extend(data["templates"])
    L.append("}")
    L.append("-- the base game's playermodels (player_manager), for advinv_carry_cycle")
    L.append("AdvInv.CarryDefaultModels = {")
    for m in data["models"]:
        L.append(f'    "{m}",')
    L.append("}")
    Path(path).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


_LUA_DECODER = r"""local data -- the decompressed records (false: couldn't be read)
local function records()
    if data == nil then
        data = util.Decompress(util.Base64Decode(P.blob) or "") or false
        if data and #data ~= P.size then data = false end
        if not data then ErrorNoHalt("[AdvInv] carry data: can't decompress it, weapons use their templates\n") end
        P.blob = nil
    end
    return data
end
local function i16(s, k)
    local v = s:byte(k) + s:byte(k + 1) * 256
    return v >= 32768 and v - 65536 or v
end
local function decodeSet(name)
    local ix, s = P.index[name], nil
    if ix then s = records() end
    if not s then return nil end
    local t, outs = {}, P.outs
    for k = ix[1] + 1, ix[1] + ix[2] * 16, 16 do
        local cls, o = P.classes[s:byte(k)], (s:byte(k + 3) - 1) * 3
        local w = t[cls]
        if not w then w = {} t[cls] = w end
        w[P.modes[s:byte(k + 1)]] = { P.bones[s:byte(k + 2)],
            Vector(i16(s, k + 4) / 100, i16(s, k + 6) / 100, i16(s, k + 8) / 100),
            Angle(i16(s, k + 10) / 10, i16(s, k + 12) / 10, i16(s, k + 14) / 10),
            Vector(outs[o + 1] / 1000, outs[o + 2] / 1000, outs[o + 3] / 1000) }
    end
    return t
end
local function decodeStack(name)
    local ix, s = P.index[name], nil
    if ix and ix[4] > 0 then s = records() end
    if not s then return nil end
    local t, c, m = {}, P.classes, P.modes
    for k = ix[3] + 1, ix[3] + ix[4] * 6, 6 do
        t[c[s:byte(k)] .. " " .. m[s:byte(k + 1)] .. "|" .. c[s:byte(k + 2)] .. " " .. m[s:byte(k + 3)]] = i16(s, k + 4) / 100
    end
    return t
end
-- (a set is decoded the first time it's asked for; a server can still add its own sets to the tables)
AdvInv.CarryOffsets = setmetatable({}, { __index = function(t, name)
    if not isstring(name) or not P.index[name] then return nil end
    local v = decodeSet(name)
    if v then rawset(t, name, v) end
    return v
end })
AdvInv.CarryStack = setmetatable({}, { __index = function(t, name)
    if not isstring(name) or not P.index[name] then return nil end
    local v = decodeStack(name)
    if v then rawset(t, name, v) end
    return v
end })
-- the names of the packed sets (the tables only hold the ones decoded so far)
function AdvInv.CarrySetNames()
    local o = {}
    for name in pairs(P.index) do o[#o + 1] = name end
    return o
end"""


def read_full(path=PATH):
    """-> data (see write): sets[set][weapon][mode] = {bone, pos, ang, out}, reps, stack, aliases,
    templates (Lua lines), models."""
    text = Path(path).read_text(encoding="utf-8")
    if "local P = {" not in text:
        return _read_verbose(text)

    def strs(name):
        return re.findall(r'"([^"]*)"', re.search(rf"^    {name} = \{{ (.*) \}},$", text, re.M).group(1))

    classes, modes, bones = strs("classes"), strs("modes"), strs("bones")
    o = [int(x) for x in re.search(r"^    outs = \{ (.*) \},$", text, re.M).group(1).split(",")]
    outs = [tuple(v / 1000 for v in o[k:k + 3]) for k in range(0, len(o), 3)]
    index = [(m.group(1), *map(int, m.group(2, 3, 4, 5)))
             for m in re.finditer(r'^        \["([^"]+)"\] = \{ (\d+), (\d+), (\d+), (\d+) \},$', text, re.M)]
    reps_block = text[text.index("    reps = {"):text.index("    size = ")]
    reps = dict(re.findall(r'^        \["([^"]+)"\] = "([^"]*)",$', reps_block, re.M))
    b64 = "".join(re.findall(r'^        "([A-Za-z0-9+/=]+)",$', text[text.index("    blob = table.concat({"):], re.M))
    blob = _unlzma(base64.b64decode(b64))
    sets, stack = {}, {}
    for name, off, n, soff, sn in index:
        s = sets.setdefault(name, {})
        for k in range(n):
            c, m, b, oi, *v = _REC.unpack_from(blob, off + k * 16)
            s.setdefault(classes[c - 1], {})[modes[m - 1]] = {
                "bone": bones[b - 1], "pos": [x / 100 for x in v[:3]], "ang": [x / 10 for x in v[3:]],
                "out": list(outs[oi - 1])}
        if sn:
            st = stack.setdefault(name, {})
            for k in range(sn):
                ca, ma, cb, mb, push = _STACK.unpack_from(blob, soff + k * 6)
                st[f"{classes[ca - 1]} {modes[ma - 1]}|{classes[cb - 1]} {modes[mb - 1]}"] = push / 100
    return {"sets": sets, "reps": reps, "stack": stack, **_tail(text)}


def _unlzma(z):
    """.lzma with its real size in the header (what util.Decompress wants) and an end marker: decoded raw."""
    d, dict_size, size = z[0], struct.unpack_from("<I", z, 1)[0], struct.unpack_from("<Q", z, 5)[0]
    lc, lp, pb = d % 9, (d // 9) % 5, d // 45
    dec = lzma.LZMADecompressor(format=lzma.FORMAT_RAW, filters=[
        {"id": lzma.FILTER_LZMA1, "lc": lc, "lp": lp, "pb": pb, "dict_size": dict_size}])
    out = dec.decompress(z[13:], max_length=size)
    assert len(out) == size, "carry data: short blob"
    return out


def _block(text, name):
    start = text.index(f"AdvInv.{name} = {{\n")
    end = text.index("\n}\n", start)
    return start, end


def _tail(text):
    s, e = _block(text, "CarryAliases")
    aliases = dict(re.findall(r'^    \["([^"]+)"\] = "([^"]+)",$', text[s:e], re.M))
    s, e = _block(text, "CarryTemplates")
    templates = [line for line in text[s:e].split("\n")[1:] if line.strip()]
    s, e = _block(text, "CarryDefaultModels")
    models = re.findall(r'^    "([^"]+)",$', text[s:e], re.M)
    return {"aliases": aliases, "templates": templates, "models": models}


def _read_verbose(text):
    """The former, unpacked file (one Lua line per entry): converted on the next write."""
    s, e = _block(text, "CarryOffsets")
    sets, reps, cur, weapon = {}, {}, None, None
    ent = re.compile(r'^            (\w+) = \{ "([^"]+)", V\(([^)]*)\), A\(([^)]*)\), V\(([^)]*)\) \},$')

    def num(g):
        return [float(x) for x in g.split(",")]

    for line in text[s:e].splitlines():
        m = re.match(r'^    \["([^"]+)"\] = \{(?: -- (.*))?$', line)
        if m:
            cur = sets.setdefault(m.group(1), {})
            reps[m.group(1)] = (m.group(2) or "").strip()
            continue
        m = re.match(r"^        (\w+) = \{$", line)
        if m and cur is not None:
            weapon = cur.setdefault(m.group(1), {})
            continue
        m = ent.match(line)
        if m and weapon is not None:
            weapon[m.group(1)] = {"bone": m.group(2), "pos": num(m.group(3)), "ang": num(m.group(4)), "out": num(m.group(5))}
    stack, cur = {}, None
    s, e = _block(text, "CarryStack")
    for line in text[s:e].splitlines():
        m = re.match(r'^    \["([^"]+)"\] = \{$', line)
        if m:
            cur = stack.setdefault(m.group(1), {})
            continue
        m = re.match(r'^        \["([^"]+)"\] = (-?[\d.]+),$', line)
        if m and cur is not None:
            cur[m.group(1)] = float(m.group(2))
    return {"sets": sets, "reps": reps, "stack": stack, **_tail(text)}


def read(path=PATH):
    """-> (sets, aliases): sets[set][weapon][mode] = {bone, pos, ang, out}; aliases[playermodel] = set
    (lowercase)."""
    d = read_full(path)
    return d["sets"], {m.lower(): v for m, v in d["aliases"].items()}


def set_of(aliases, sets, playermodel):
    name = aliases.get(playermodel.lower(), "default")
    return name if name in sets else "default"


def apply_locks(locks, path=PATH):
    """Writes the approved carry positions (fit_locks: class 'carry:...' -> {playermodel: (pos, ang,
    size)}) into the playermodel's set. Returns how many entries changed."""
    data = read_full(path)
    sets = data["sets"]
    aliases = {m.lower(): v for m, v in data["aliases"].items()}
    changed = 0
    for cls, per in locks.items():
        wm = split_class(cls)
        if not wm:
            continue
        for pm, (p, a, _s) in per.items():
            e = sets.get(set_of(aliases, sets, pm), {}).get(wm[0], {}).get(wm[1])
            if e is None:
                continue
            new_p, new_a = [round(x, 2) for x in p[:3]], [round(x, 1) for x in a[:3]]
            if [round(x, 2) for x in e["pos"]] != new_p or [round(x, 1) for x in e["ang"]] != new_a:
                e["pos"], e["ang"] = new_p, new_a
                changed += 1
    if changed:
        write(data, path)
    return changed
