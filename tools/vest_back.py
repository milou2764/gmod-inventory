"""How thick each vest of the compatible addons is on the back, where slung weapons rest (dev tool,
not in the .gma). Writes lua/advinv/cl_vest_back.lua: AdvInv.VestBackThickness[class] = units.

The vest is placed on male_07 by its fit (sh_compat_data.lua, the fit on male_07), then over the
shoulder blades (a band 6 units either side of the spine, from 4 to 18 units under the base of the
neck) each 1-unit cell compares the backmost point of the vest (its surface, sampled) with the
backmost point of the torso around it (its vertices within NEAR units: they are a few units apart).
A back mostly bare (straps of a chest rig, under COVER of the band) counts 0; else the median of the
covered cells. The game uses it before the armour rule (cl_carry.lua).

    MDL_EXTRA_DIRS=... python vest_back.py
"""
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import anim0  # noqa: E402
import fit_compat as fc  # noqa: E402
import fit_items as fi  # noqa: E402
import mdl_render as mr  # noqa: E402

TOOLS = Path(__file__).resolve().parent
DATA = TOOLS.parent / "lua" / "advinv" / "sh_compat_data.lua"
OUT = TOOLS.parent / "lua" / "advinv" / "cl_vest_back.lua"
SPINE4 = "ValveBiped.Bip01_Spine4"
BAND, DOWN = 6.0, (4.0, 18.0)
COVER = 0.5
NEAR = 2.5

body = fi.Body(fi.REF)
torso = body.verts(fi.TORSO)
neck = body.world["ValveBiped.Bip01_Neck1"][:3, 3]
fwd = body.eyes[:3, 0].copy()
fwd[2] = 0
fwd /= np.linalg.norm(fwd)
back = -fwd
side = np.cross([0, 0, 1.0], fwd)
cx = neck @ side


def band_cells(P):
    """backmost point (along back) of points P per 1-unit cell (sideways, height) of the band."""
    s, z, b = P @ side - cx, P[:, 2], P @ back
    keep = (np.abs(s) <= BAND) & (z <= neck[2] - DOWN[0]) & (z >= neck[2] - DOWN[1])
    out = {}
    for i, j, v in zip(np.floor(s[keep]).astype(int), np.floor(z[keep]).astype(int), b[keep]):
        if v > out.get((i, j), -np.inf):
            out[(i, j)] = v
    return out


def body_back_cells():
    """backmost torso point around each cell of the band (vertices within NEAR units)."""
    s, z, b = torso @ side - cx, torso[:, 2], torso @ back
    out = {}
    for i in range(int(-BAND), int(BAND) + 1):
        for j in range(int(np.floor(neck[2] - DOWN[1])), int(np.floor(neck[2] - DOWN[0])) + 1):
            near = (s - (i + 0.5)) ** 2 + (z - (j + 0.5)) ** 2 <= NEAR ** 2
            if near.any():
                out[(i, j)] = b[near].max()
    return out


body_cells = body_back_cells()
text = DATA.read_text(encoding="utf-8")
items = re.findall(r'class = "([^"]+)", model = "([^"]+)",\s*name = \{[^}]*\}, slot = "Vest"[^\n]*\n\s*attach = \{ bone = "([^"]+)", '
                   r'pos = Vector\(([^)]*)\), ang = Angle\(([^)]*)\), scale = ([\d.]+) \}', text)
rows = []
for cls, model, bone, pos, ang, scale in items:
    P = fc.surface_points(model)
    R = mr.rot_matrix(*[float(v) for v in ang.split(",")])
    local = (float(scale) * P) @ R.T + np.array([float(v) for v in pos.split(",")])
    W = body.world[bone]
    vest = local @ W[:3, :3].T + W[:3, 3]
    cells = band_cells(vest)
    gaps = [cells[c] - body_cells[c] for c in cells if c in body_cells and cells[c] > body_cells[c] - 0.5]
    cover = len(gaps) / max(1, len(body_cells))
    thick = round(float(np.median(gaps)), 1) if gaps and cover >= COVER else 0.0
    rows.append((cls, max(0.0, thick), cover))
    print(f"{cls:48} back {max(0.0, thick):4.1f}  cover {cover:.0%}")

lines = ["-- Generated by tools/vest_back.py: how thick each vest of the compatible addons is on the back",
         "-- (units), where slung weapons rest (cl_carry.lua).",
         "AdvInv.VestBackThickness = AdvInv.VestBackThickness or {}"]
for cls, thick, _ in rows:
    lines.append(f'AdvInv.VestBackThickness["{cls}"] = {thick:g}')
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(rows)} vests -> {OUT}")
