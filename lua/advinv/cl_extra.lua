--[[
    Small things, client side: the chat command opens the inventory, the pickup key (Options >
    Advanced Inventory > Inventory; none by default) takes the item looked at, and the theme setting.
--]]
local I = AdvInv

net.Receive("advinv_open_inventory", function()
    if AdvInv.OpenInventory and hook.Run("AdvInv_CanOpen", LocalPlayer()) ~= false then AdvInv.OpenInventory() end
end)

local KEYBINDS_FILE = "advinv/keybinds.txt"

function AdvInv.PickupKey()
    return (AdvInv.keybinds and AdvInv.keybinds.pickup) or KEY_NONE
end

local released = true
hook.Add("Think", "AdvInv_PickupKey", function()
    local key = AdvInv.PickupKey()
    if not key or key == KEY_NONE or key <= 0 then return end
    if input.IsKeyDown(key) then
        if not released then return end
        released = false
        if vgui.CursorVisible() or gui.IsGameUIVisible() then return end
        net.Start("advinv_pickup")
        net.SendToServer()
    else
        released = true
    end
end)

hook.Add("PopulateToolMenu", "AdvInv_Extra", function()
    spawnmenu.AddToolMenuOption("Options", "Advanced Inventory", "advinv_more", I.L("options_more"), "", "", function(panel)
        panel:ClearControls()
        panel:Help(I.L("options_pickup_key"))
        local binder = vgui.Create("AdvInvBinder")
        binder:SetValue(AdvInv.PickupKey())
        binder.OnChange = function(_, val)
            AdvInv.keybinds = AdvInv.keybinds or {}
            AdvInv.keybinds.pickup = val
            file.CreateDir("advinv")
            file.Write(KEYBINDS_FILE, util.TableToJSON(AdvInv.keybinds))
        end
        panel:AddItem(binder)
        local combo = panel:ComboBox(I.L("options_theme"), "advinv_theme")
        for _, name in ipairs({ "dark", "light", "military" }) do combo:AddChoice(I.L("theme_" .. name), name) end
        panel:CheckBox(I.L("options_hover_text"), "advinv_hover_text")
    end)
end)

--[[
    Spawn menu: inventory items with no icon of their own (worn gear, crates...) show their model,
    like the props: the icon's image is drawn by a model image instead (generated by the game).
--]]
local function inventoryEntity(class)
    return isstring(class) and (string.StartWith(class, "advinv_") or AdvInv.ClassID[class] ~= nil)
end

-- (on the client, util.IsValidModel is only true once the model has been loaded: the spawn menu is
-- built before most of them are)
local function modelExists(mdl)
    return isstring(mdl) and mdl ~= "" and (util.IsValidModel(mdl) or file.Exists(mdl, "GAME"))
end

local function wrapEntityIcons()
    if not (GAMEMODE and GAMEMODE.IsSandboxDerived and spawnmenu and spawnmenu.GetContentType) then return end
    local cur = spawnmenu.GetContentType("entity")
    if not cur then return end
    -- (a Lua refresh wraps the game's maker again, not our previous wrapper)
    local make = cur == AdvInv.EntityIconMaker and AdvInv.EntityIconBase or cur
    AdvInv.EntityIconBase = make
    local function maker(container, obj)
        local icon = make(container, obj)
        if not (IsValid(icon) and IsValid(icon.Image) and obj and inventoryEntity(obj.spawnname)) then return icon end
        local mat = obj.material and Material(obj.material)
        if mat and not mat:IsError() then return icon end -- it has an icon
        local t = scripted_ents.Get(obj.spawnname)
        local mdl = t and t.Model
        if not modelExists(mdl) then return icon end
        local img
        if t.PhysHull and AdvInv.UsesGearIcon and AdvInv.UsesGearIcon(obj.spawnname) then
            -- gear drawn from a playermodel: the gear alone, as worn (the model is the whole playermodel)
            img = vgui.Create("AdvInvGearIcon", icon)
            img:SetItemClass(obj.spawnname)
            img:SetMouseInputEnabled(false)
            img:SetPaintedManually(true)
            icon.Image.PaintAt = function(_, x, y, w, h)
                img:SetPos(x, y)
                img:SetSize(w, h)
                img:PaintManual()
            end
            return icon
        end
        img = vgui.Create("ModelImage", icon)
        img:SetMouseInputEnabled(false)
        img:SetKeyboardInputEnabled(false)
        img:SetPaintedManually(true)
        img:SetModel(mdl, t.Skin or t.skin or 0)
        icon.Image.PaintAt = function(_, x, y, w, h)
            img:SetPos(x, y)
            img:SetSize(w, h)
            img:PaintManual()
        end
        return icon
    end
    AdvInv.EntityIconMaker = maker
    spawnmenu.AddContentType("entity", maker)
end
hook.Add("OnGamemodeLoaded", "AdvInv_SpawnIcons", wrapEntityIcons)
wrapEntityIcons() -- (Lua refresh)

-- keybinds file: the pickup key is read with the inventory key (cl_keybinds.lua)
if AdvInv.keybinds and AdvInv.keybinds.pickup == nil then
    local saved = file.Read(KEYBINDS_FILE, "DATA")
    local tab = saved and util.JSONToTable(saved)
    if tab and tab.pickup then AdvInv.keybinds.pickup = tab.pickup end
end
