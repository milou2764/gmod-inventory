--[[
    Compatibility with Workshop addons (the list: sh_compat_data.lua, generated by
    tools/fit_compat.py from tools/compat_packs.py). Their models are NOT part of this addon: when
    a server has one of these addons installed, its models become inventory items (helmets,
    backpacks, vests), fitted to every default playermodel (cl_fits_compat.lua).

    Every compatibility item is registered (its ID stays reserved and saved items keep their class),
    but it is spawnable, given by admins and shown only where its model is there. The server makes
    its players download the installed addons (advinv_compat_download 1).

    IDs 1000-1999 (sent on 16 bits). Never change one: they are saved.
--]]
local I = AdvInv
I.CompatPacks = I.CompatPacks or {}

local download = CreateConVar("advinv_compat_download", "1", { FCVAR_ARCHIVE },
    "Players download the Workshop addons the inventory is compatible with, when the server has them", 0, 1)

local BASES = { Helmet = "advinv_base_helmet", Rucksack = "advinv_base_rucksack", Vest = "advinv_base_pocketvest" }

-- Is this addon here? Its first model; an addon that replaces a base game model also needs one of
-- its own materials, and a model that is not the base game's one; an addon drawn with another game's
-- materials (mount = "tf": the TF2 hats) needs that game mounted (else it is all magenta).
local function installed(pack)
    local first = pack.items[1]
    if not (first and file.Exists(first.model, "GAME")) then return false end
    if pack.mount and not IsMounted(pack.mount) then return false end
    if pack.probeMaterial then
        if not file.Exists(pack.probeMaterial, "GAME") then return false end
        if (pack.baseModelSize or 0) > 0 and file.Size(first.model, "GAME") == pack.baseModelSize then return false end
    end
    return true
end

function I.CompatItemAvailable(class)
    local t = scripted_ents.GetStored(class)
    return not (t and t.t and t.t.AdvInvAvailable == false)
end

local function register(pack, it, here)
    local ENT = {}
    ENT.Type = "anim"
    ENT.Base = BASES[it.slot] or "advinv_base_gear"
    if it.slot == "Vest" and (it.load or 0) <= 0 then ENT.Base = "advinv_base_vest" end
    ENT.PrintName = I.T(it.name[1], it.name[2])
    ENT.Category = I.T(pack.category[1], pack.category[2])
    ENT.Author = pack.title .. " (Workshop " .. pack.wid .. ")"
    ENT.Information = I.T("Model of the Workshop addon \"" .. pack.title .. "\"",
        "Modèle de l'addon du Workshop « " .. pack.title .. " »")
    ENT.AdvInvAvailable = here and file.Exists(it.model, "GAME") or false
    ENT.Spawnable = ENT.AdvInvAvailable
    ENT.AdvInvCompat = pack.key
    ENT.AdvInvCategory = it.slot
    ENT.Model = it.model
    ENT.Mass = it.mass
    ENT.Armor = it.armor or 0 -- (0: none; nil would take the base's 100)
    if it.slot ~= "Helmet" then ENT.MaxLoad = it.load or 0 end
    if it.blocks then ENT.BlocksCarryZones = { [it.blocks] = true } end
    ENT.Attach = it.attach
    scripted_ents.Register(ENT, it.class)
    I.ClassID[it.class] = it.id
end

function I.RegisterCompat()
    for _, pack in ipairs(I.CompatPacks) do
        local here = installed(pack)
        pack.installed = here
        for _, it in ipairs(pack.items) do register(pack, it, here) end
        if SERVER and here and download:GetBool() and pack.wid then resource.AddWorkshop(pack.wid) end
    end
end

I.RegisterCompat()
