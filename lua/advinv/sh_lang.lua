--[[
    Languages of the inventory: English (default) and French; German, Spanish and Russian in
    sh_lang_more.lua.

    The server chooses the language for everyone (server.cfg):
        advinv_language en      -- English
        advinv_language fr      -- French
    Item names are read when the addon loads: change the language, then restart the map.

    In code:
        AdvInv.L("msg_no_room_for", name)   -- text by key (string.format arguments)
        AdvInv.T("Bucket", "Seau")           -- inline English / French pair (item names)
    To add a language, add a table to AdvInv.Lang (missing keys fall back to English).
--]]
