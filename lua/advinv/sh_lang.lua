function I.Language()
    local code = string.lower(language:GetString())
    return I.Lang[code] and code or "en"
end

-- Text for a key in the server's language (English if the key is missing there).
function I.L(key, ...)
    local s = I.Lang[I.Language()][key] or I.Lang.en[key] or key
    if select("#", ...) > 0 then s = string.format(s, ...) end
    return s
end

-- Inline English / French pair (item names, spawn menu categories).
function I.T(en, fr)
    return (I.Language() == "fr" and fr) or en
end

-- Container names, gear slot labels and "your ..." forms, looked up by name in the current language
-- (I.ContainerNames.Rucksack, I.SlotLabels.Helmet, I.SlotYour.NVGs).
local function lookup(prefix)
    return setmetatable({}, { __index = function(_, k) return I.Lang[I.Language()][prefix .. k] or I.Lang.en[prefix .. k] end })
end
I.SlotLabels = lookup("slot_")
I.SlotYour = lookup("your_")
I.ContainerNamesLang = lookup("cont_")
